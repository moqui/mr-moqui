//! TypeScript declarations from the loaded definitions (`plans/archive/TypeGeneration.md`). A tool on the definition caches: it
//! reads the entity model, the service registry and the screen definitions the runtime uses, and is not on the request
//! path. `moqui types` is the entry point.
//!
//! The output is `.d.ts` files plus one small shape module, and a `tsconfig.json` so `tsc --noEmit -p <dir>` checks them:
//!
//! - `moqui-host.d.ts`: decimals, timestamps, entity values, lists and finds, the server `ec` and `sri`, the static helpers,
//!   the unwrapped projection, the browser `ec`, and the server-static qvt package types. Fixed text plus the page,
//!   header and credential names from the Rust constants.
//! - `moqui-globals.d.ts`: `ec`, `context`, `result`, `sri` and the helpers as names a server script sees.
//! - `entities.d.ts`, `services.d.ts`, `screens.d.ts`: from the definitions.
//! - `shape.ts`: the package keys as values, for client code.
//!
//! Nothing here changes the runtime. The QuickJS host does not read these files.

mod entities;
mod screens;
mod services;
mod ts;

use std::path::{Path, PathBuf};
use std::sync::Arc;

use moqui_db::model::EntityModel;

use moqui_core::context::{Error, ExecutionContextFactory};
use moqui_core::screen::statics::{HEADER_SUFFIXES, MERGED_MODULE, PAGE_SUFFIXES};
use moqui_core::screen::{ScreenDef, ScreenFacade};
use moqui_core::service::define::ServiceDef;
use moqui_core::web::CREDENTIAL_PARAMETER_NAMES;

pub(crate) const HEADER: &str = "// Generated by `moqui types` from the loaded definitions. Do not edit.\n";

const HOST: &str = include_str!("moqui-host.d.ts");
const GLOBALS: &str = include_str!("moqui-globals.d.ts");

const TSCONFIG: &str = r#"{
    "compilerOptions": {
        "target": "ES2022",
        "lib": ["ES2022"],
        "module": "ES2022",
        "strict": true,
        "noEmit": true,
        "types": []
    },
    "include": ["*.d.ts", "*.ts"]
}
"#;

/// The generated files by name, and notes on what was left out.
#[derive(Debug, Default)]
pub struct TypeFiles {
    files: Vec<(String, String)>,
    /// Screens that did not load and `auto-parameters` that could not be expanded.
    pub notes: Vec<String>,
}

impl TypeFiles {
    pub fn files(&self) -> &[(String, String)] {
        &self.files
    }

    /// The text of the file `name`.
    pub fn get(&self, name: &str) -> Option<&str> {
        self.files
            .iter()
            .find(|(file, _)| file == name)
            .map(|(_, text)| text.as_str())
    }

    /// Write every file into `dir`, creating it.
    ///
    /// # Errors
    ///
    /// Returns an error when the directory or a file cannot be written.
    pub fn write(&self, dir: &Path) -> Result<(), Error> {
        std::fs::create_dir_all(dir).map_err(|err| Error::new(format!("{}: {err}", dir.display())))?;
        for (name, text) in &self.files {
            let path = dir.join(name);
            std::fs::write(&path, text).map_err(|err| Error::new(format!("{}: {err}", path.display())))?;
        }
        Ok(())
    }
}

fn union(names: &[&str]) -> String {
    names.iter().map(|name| ts::quote(name)).collect::<Vec<_>>().join(" | ")
}

fn array(names: &[&str]) -> String {
    names.iter().map(|name| ts::quote(name)).collect::<Vec<_>>().join(", ")
}

/// `moqui-host.d.ts`: the fixed host text, then the names it takes from the Rust constants.
fn host_text() -> String {
    format!(
        "{HEADER}{HOST}\n// ---- from the Rust constants ----\n\n\
         /** The keys a form-list's pagination sets, after the list name. */\n\
         type MoquiPageSuffix = {};\n\
         /** The request names of a form-list header field, after the field name. */\n\
         type MoquiHeaderSuffix = {};\n\
         /** Names `stripCredentialParameters` removes, compared in lower case. */\n\
         type MoquiCredentialName = {};\n",
        union(&PAGE_SUFFIXES),
        union(&HEADER_SUFFIXES),
        union(&CREDENTIAL_PARAMETER_NAMES)
    )
}

/// `tools.d.ts`: the type of each tool whose tool factory declares one, merged into `MoquiToolMap`.
fn tools_text(declarations: &[(String, &str)]) -> String {
    let mut text = format!(
        "{HEADER}// The tools of the linked component crates, by tool factory name.\n\ninterface MoquiToolMap {{\n"
    );
    for (name, declaration) in declarations {
        text.push_str(&format!("    {}: {};\n", ts::quote(name), declaration.trim()));
    }
    text.push_str("}\n");
    text
}

/// `shape.ts`: the server-static qvt package keys (`plans/archive/QvtServerStatic.md`) as values.
fn shape_text() -> String {
    format!(
        "{HEADER}// The server-static qvt package keys as values, for client code that reads a package or a form-list package.\n\n\
         export const PAGE_SUFFIXES = [{}] as const satisfies readonly MoquiPageSuffix[];\n\
         export const HEADER_SUFFIXES = [{}] as const satisfies readonly MoquiHeaderSuffix[];\n\
         export const CREDENTIAL_NAMES = [{}] as const satisfies readonly MoquiCredentialName[];\n\n\
         /** The keys a form-list `list` loses from the screen package and has in its own package. */\n\
         export function pageKeys<L extends string>(list: L): MoquiPageKey<L>[] {{\n\
         \x20   return PAGE_SUFFIXES.map((suffix) => `${{list}}${{suffix}}` as MoquiPageKey<L>);\n\
         }}\n\n\
         /** Where a form-single's server lookups are kept in the screen package. */\n\
         export function extraKey(form: string): `mqExtra_${{string}}` {{\n\
         \x20   return `mqExtra_${{form}}`;\n\
         }}\n\n\
         /** The key of a drop-down's options: the field's sub-node index among its children, the widget's index in the sub-node. */\n\
         export function optionKey(form: string, field: string, subIndex: number, widgetIndex: number): `mqOpt_${{string}}` {{\n\
         \x20   return `mqOpt_${{form}}_${{field}}_${{subIndex}}_${{widgetIndex}}`;\n\
         }}\n\n\
         /** The props of a server-static qvt screen's template: its package and the browser `ec`. */\n\
         export type ScreenProps<S extends keyof MoquiScreenPackages> = MoquiStaticScope<MoquiScreenPackages[S]>;\n\
         /** The body of `GET {{screen}}/actions/{{formName}}`, by `location#formName`. */\n\
         export type FormListProps<F extends keyof MoquiFormListPackages> = MoquiFormListPackages[F];\n",
        array(&PAGE_SUFFIXES),
        array(&HEADER_SUFFIXES),
        array(&CREDENTIAL_PARAMETER_NAMES)
    )
}

/// The files for these definitions. The emitters take the parsed model only, so tests run them on fixtures.
fn assemble_files(
    model: Option<&EntityModel>,
    services: &[ServiceDef],
    screens: &[screens::ScreenSource<'_>],
    screen_failures: &[(String, String)],
) -> TypeFiles {
    let mut files = Vec::new();
    files.push(("moqui-host.d.ts".to_string(), host_text()));
    files.push(("moqui-globals.d.ts".to_string(), format!("{HEADER}{GLOBALS}")));
    let entities = match model {
        Some(model) => entities::emit(model),
        None => format!("{HEADER}// No entity model is loaded.\n"),
    };
    files.push(("entities.d.ts".to_string(), entities));
    let (services_text, mut notes) = services::emit(services, model);
    files.push(("services.d.ts".to_string(), services_text));
    files.push((
        "screens.d.ts".to_string(),
        screens::emit(screens, model, screen_failures),
    ));
    files.push(("shape.ts".to_string(), shape_text()));
    files.push(("tsconfig.json".to_string(), TSCONFIG.to_string()));
    notes.extend(
        screen_failures
            .iter()
            .map(|(location, reason)| format!("screen {location} did not load: {reason}")),
    );
    TypeFiles { files, notes }
}

/// The location a screen file is known by: `component://` below the component that holds it.
fn location_of(factory: &ExecutionContextFactory, path: &Path) -> String {
    let canonical = path.canonicalize().unwrap_or_else(|_| path.to_path_buf());
    let relative = |root: &Path| {
        let root = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
        canonical
            .strip_prefix(&root)
            .ok()
            .map(|rest| rest.to_string_lossy().replace('\\', "/"))
    };
    for component in factory.components() {
        if let Some(rest) = relative(&component.location) {
            return format!("component://{}/{rest}", component.name);
        }
    }
    canonical.to_string_lossy().into_owned()
}

/// What the screen emitter reads of each loaded screen: the assembled forms, and whether qvt is static for it.
fn screen_sources<'a>(
    facade: &ScreenFacade,
    factory: &ExecutionContextFactory,
    defs: &'a [(String, Arc<ScreenDef>)],
) -> Vec<screens::ScreenSource<'a>> {
    let mut sources = Vec::new();
    for (location, def) in defs {
        let mut forms = Vec::new();
        for (name, form) in &def.forms {
            let assembled = if form.dynamic {
                None
            } else {
                moqui_core::screen::form::assemble(facade, factory, def, name)
                    .and_then(|instance| instance.node())
                    .ok()
            };
            let Some(node) = assembled.or_else(|| form.node.node().ok()) else {
                continue;
            };
            forms.push(screens::FormSource {
                name: name.clone(),
                list: form.list,
                dynamic: form.dynamic,
                node,
            });
        }
        let macro_location = def
            .macro_template_location("qvt")
            .map(str::to_string)
            .or_else(|| {
                facade
                    .text_output("qvt")
                    .map(|output| output.macro_template_location.clone())
            })
            .unwrap_or_else(|| MERGED_MODULE.to_string());
        let server_static = def.is_server_static("qvt")
            && moqui_core::screen::statics::eligibility_of(facade, factory, def, &macro_location, false).eligible;
        sources.push(screens::ScreenSource {
            location: location.clone(),
            def,
            forms,
            server_static,
        });
    }
    sources
}

/// Declarations for the definitions `factory` loads: its entity model (when an entity facade is attached), the configured
/// service files, and the screen files in `screen_files`. A screen that does not load is a note, not an error.
///
/// # Errors
///
/// Returns an error when the service files cannot be read.
pub fn generate(factory: &Arc<ExecutionContextFactory>, screen_files: &[PathBuf]) -> Result<TypeFiles, Error> {
    let context = factory.new_context();
    let _entered = context.enter();
    let _authz = context.disable_authz();
    moqui_core::service::load_definitions()?;
    let services = moqui_core::service::define::registered()?;
    let facade = ScreenFacade::of(factory);
    let mut defs = Vec::new();
    let mut failures = Vec::new();
    for path in screen_files {
        let location = location_of(factory, path);
        match facade.screen_def(factory, &location) {
            Ok(def) => defs.push((location, def)),
            Err(err) => failures.push((location, err.to_string())),
        }
    }
    let sources = screen_sources(&facade, factory, &defs);
    let mut files = match factory.entity() {
        Some(entity) => entity.with_model(|model| assemble_files(Some(model), &services, &sources, &failures)),
        None => assemble_files(None, &services, &sources, &failures),
    };
    files
        .files
        .push(("tools.d.ts".to_string(), tools_text(&factory.tool_type_declarations())));
    Ok(files)
}

/// Parse `xml`, a test fixture, as the root of an entity, service or screen document.
#[cfg(test)]
fn fixture_root(name: &str) -> moqui_lib::node::MNode {
    let path = testdata().join(name);
    moqui_lib::node::MNode::parse_file(&path).unwrap_or_else(|err| panic!("{}: {err}", path.display()))
}

#[cfg(test)]
fn testdata() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/typegen/testdata")
}

