//! Errors of the oxide engine as the QuickJS path makes them (plans/Script-Engine-Oxide.md section 4): the text
//! `Error: <message>` and the `stack` below it (`    at <eval> (eval_script:1:5)`, the same form on both engines),
//! the security kind and retry seconds the thrown error carries (`moquiErrorKind`, `moquiRetryAfter`), and a plain
//! `Error` thrown from a host function.

use std::any::Any;

use quickjs_oxide::engine::api::core::{CallableRef, Js, JsString, NativeErrorKind, RuntimeError, Value};

use crate::context::Error;

/// The framework error of an oxide run that ended with `err`. `js` reads the thrown error's properties.
pub(super) fn runtime_error<J: Js>(js: &mut J, err: RuntimeError) -> Error {
    match err {
        RuntimeError::Exception(thrown) => exception_error(js, &thrown),
        RuntimeError::Interrupted => Error::script("Error: interrupted\n    at <eval> (eval_script)\n"),
        RuntimeError::OutOfMemory => Error::script("Error: out of memory"),
        RuntimeError::Compile(compile) => Error::script(format!("Error: {compile}")),
        RuntimeError::Poisoned => Error::new("the quickjs-oxide runtime is poisoned: a host function panicked"),
        other => Error::new(format!("quickjs-oxide: {other}")),
    }
}

/// `Error: <message>` and the stack, as rquickjs's `CaughtError` shows an exception; a thrown value that is not an
/// error, as it shows such a value.
fn exception_error<J: Js>(js: &mut J, thrown: &Value) -> Error {
    let object = thrown.as_object().cloned();
    let is_error = object
        .as_ref()
        .is_some_and(|object| js.is_error_object(object).unwrap_or(false));
    let Some(object) = object.filter(|_| is_error) else {
        let shown = js.print_value(thrown).unwrap_or_else(|_| "a value".to_string());
        return Error::script(format!("Exception generated by quickjs: {shown}\n"));
    };
    let mut text = String::from("Error:");
    if let Some(message) = text_property(js, &object, "message") {
        text.push(' ');
        text.push_str(&message);
    }
    if let Some(stack) = text_property(js, &object, "stack") {
        text.push('\n');
        text.push_str(&stack);
    }
    let mut err = Error::script(text);
    if let Some(kind) = text_property(js, &object, crate::script::runtime::KIND_PROPERTY)
        .and_then(|name| crate::script::runtime::carried_kind(&name))
    {
        err = err.with_kind(kind);
    }
    let retry = property(js, &object, crate::script::runtime::RETRY_AFTER_PROPERTY).and_then(|value| value.as_number());
    match retry {
        #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
        Some(seconds) if seconds >= 0.0 => err.with_retry_after(seconds as u64),
        _ => err,
    }
}

fn property<J: Js>(js: &mut J, object: &quickjs_oxide::engine::api::core::ObjectRef, name: &str) -> Option<Value> {
    let key = quickjs_oxide::engine::api::core::PropertyKey::from_js_string(JsString::try_from_utf8(name).ok()?);
    js.get_property(object, &key).ok()
}

/// A property as text; `None` when it is undefined or null.
fn text_property<J: Js>(
    js: &mut J,
    object: &quickjs_oxide::engine::api::core::ObjectRef,
    name: &str,
) -> Option<String> {
    match property(js, object, name)? {
        Value::Undefined | Value::Null => None,
        Value::String(text) => Some(text.to_utf8_lossy()),
        other => js.to_js_string(&other).ok().map(|text| text.to_utf8_lossy()),
    }
}

/// The error to throw from a host function for `message`: a plain `Error`, as QuickJS's `throw_message` makes, with
/// the stack of the running frames.
pub(super) fn throw_plain<J: Js>(js: &mut J, error: &CallableRef, message: &str) -> RuntimeError {
    let Ok(text) = JsString::try_from_utf8(message) else {
        return RuntimeError::OutOfMemory;
    };
    match js.construct(error, &[Value::String(text)]) {
        Ok(thrown) => RuntimeError::Exception(thrown),
        Err(_) => js.throw_error(NativeErrorKind::Type, message),
    }
}

/// The text of a panic's payload.
pub(super) fn panic_message(payload: Box<dyn Any + Send>) -> String {
    if let Some(message) = payload.downcast_ref::<&str>() {
        return (*message).to_string();
    }
    if let Some(message) = payload.downcast_ref::<String>() {
        return message.clone();
    }
    "host callback panicked".to_string()
}
