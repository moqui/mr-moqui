//! A JavaScript runtime of its own, with no `ec` and no host functions, for the checks that run a library's code (the
//! Vue compiler's template checks, OpenUI Lang's parser, a Vue SFC script's compile check): a quickjs-oxide runtime with
//! a heap cap, and an interrupt the caller answers (its deadline).

use quickjs_oxide::engine::api::core::{
    Context, HeapLimits, Host, Js, JsString, PropertyKey, Runtime, RuntimeError, RuntimeOptions, Value,
};

/// The runtime and its realm.
pub struct Standalone {
    context: Context,
    // the context is the runtime's; it goes first
    _runtime: Runtime,
}

/// The runtime's host: UTC and the system clock (the default's), the caller's interrupt.
struct Interrupt(Box<dyn Fn() -> bool>);

impl Host for Interrupt {
    fn interrupt(&mut self) -> bool {
        (self.0)()
    }
}

impl Standalone {
    /// A runtime whose heap is at most `memory_limit` bytes, stopped when `interrupt` answers true.
    pub fn start(memory_limit: usize, interrupt: impl Fn() -> bool + 'static) -> Self {
        let options = RuntimeOptions {
            heap: HeapLimits {
                max_bytes: memory_limit,
            },
            ..RuntimeOptions::default()
        };
        let runtime = Runtime::with_host(Interrupt(Box::new(interrupt)), options);
        let context = runtime.context();
        Standalone {
            context,
            _runtime: runtime,
        }
    }

    /// Run `source` (a script) for what it defines.
    ///
    /// # Errors
    ///
    /// The thrown error as [`Self::text`] words it.
    pub fn run(&self, source: &str) -> Result<(), String> {
        let mut context = self.context.clone();
        context
            .eval(source)
            .map(|_| ())
            .map_err(|err| error_text(&mut context, err))
    }

    /// The value of `source` (a script whose value is a string), as text.
    ///
    /// # Errors
    ///
    /// A thrown error is `Error: <message>` and its stack; a value that is not a string is named.
    pub fn text(&self, source: &str) -> Result<String, String> {
        let mut context = self.context.clone();
        let value = context.eval(source).map_err(|err| error_text(&mut context, err))?;
        match value {
            Value::String(text) => Ok(text.to_utf8_lossy()),
            other => {
                let shown = context.print_value(&other).unwrap_or_default();
                Err(format!("Error converting from js '{shown}' into type 'String'"))
            }
        }
    }
}

/// A thrown error as `Error: <message>` and its stack; a thrown value that is not an error as it prints.
fn error_text(js: &mut impl Js, err: RuntimeError) -> String {
    let RuntimeError::Exception(thrown) = err else {
        return format!("Error: {err}");
    };
    let object = thrown.as_object().cloned();
    let Some(object) = object.filter(|object| js.is_error_object(object).unwrap_or(false)) else {
        return format!(
            "Exception generated by quickjs: {}",
            js.print_value(&thrown).unwrap_or_default()
        );
    };
    let mut text = String::from("Error:");
    let mut property = |name: &str| -> Option<String> {
        let key = PropertyKey::from_js_string(JsString::try_from_utf8(name).ok()?);
        match js.get_property(&object, &key).ok()? {
            Value::String(text) => Some(text.to_utf8_lossy()),
            _ => None,
        }
    };
    if let Some(message) = property("message") {
        text.push(' ');
        text.push_str(&message);
    }
    if let Some(stack) = property("stack") {
        text.push('\n');
        text.push_str(&stack);
    }
    text
}

#[cfg(test)]
mod tests {
    use super::Standalone;

    #[test]
    fn a_runtime_runs_text_shows_errors_and_stops_at_its_interrupt() {
        let js = Standalone::start(16 * 1024 * 1024, || false);
        js.run("globalThis.twice = (x) => x + x").expect("defines");
        assert_eq!(js.text("twice('ab')").as_deref(), Ok("abab"));
        let thrown = js
            .text("(function f() { throw new SyntaxError('no') })()")
            .expect_err("throws");
        assert!(thrown.starts_with("Error: no\n"), "{thrown}");
        let stopped = Standalone::start(16 * 1024 * 1024, || true);
        assert!(stopped.run("for (;;) {}").is_err());
    }
}
